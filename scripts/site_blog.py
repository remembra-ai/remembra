def rfc822(day: dt.date) -> str:
    return format_datetime(dt.datetime(day.year, day.month, day.day, tzinfo=dt.UTC), usegmt=True)


def render_feed(entries: list[Post], through: dt.date) -> str:
    """landing/feed.xml: RSS 2.0 for the latest posts. Its dates come from the posts, never the clock."""
    latest = entries[:FEED_ITEMS]
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">',
        "  <channel>",
        f"    <title>{xml_escape(BLOG_NAME)}</title>",
        f"    <link>{SITE}/blog</link>",
        f"    <description>{xml_escape(BLOG_DESCRIPTION)}</description>",
        "    <language>en-us</language>",
    ]
    if latest:
        lines.append(f"    <lastBuildDate>{rfc822(max(p.modified(through) for p in latest))}</lastBuildDate>")
    lines.append(f'    <atom:link href="{SITE}/feed.xml" rel="self" type="application/rss+xml"/>')
    for post in latest:
        lines += [
            "    <item>",
            f"      <title>{xml_escape(post.title)}</title>",
            f"      <link>{post.url}</link>",
            f'      <guid isPermaLink="true">{post.url}</guid>',
            f"      <pubDate>{rfc822(post.date)}</pubDate>",
            f"      <description>{xml_escape(post.description)}</description>",
            *(f"      <category>{xml_escape(tag)}</category>" for tag in post.tags),
            "    </item>",
        ]
    lines += ["  </channel>", "</rss>"]
    return "\n".join(lines) + "\n"


BLOG_URL_LINE = re.compile(r"^([ \t]*)<url><loc>(https://remembra\.dev/blog(?:/[^<]*)?)</loc>(.*)</url>[ \t]*$")
URL_TAIL = re.compile(r"<changefreq>.*$")
TAIL_INDEX = "<changefreq>monthly</changefreq><priority>0.4</priority>"
TAIL_POST = "<changefreq>monthly</changefreq><priority>0.5</priority>"


def render_sitemap(xml: str, entries: list[Post], through: dt.date) -> str:
    """sitemap.xml with its /blog lines rewritten (loc and lastmod; a line's changefreq and priority are kept).

    Every other line, the <!-- @crew-url --> line site_partials.py owns among them, is returned byte for byte.
    """
    lines = xml.splitlines(keepends=True)
    kept: list[str] = []
    tails: dict[str, str] = {}
    at: int | None = None
    indent = "  "
    for line in lines:
        m = BLOG_URL_LINE.match(line.rstrip("\r\n"))
        if not m:
            kept.append(line)
            continue
        if at is None:
            at, indent = len(kept), m.group(1)
        tail = URL_TAIL.search(m.group(3))
        if tail:
            tails[m.group(2)] = tail.group(0)
    if at is None:
        closing = [n for n, line in enumerate(kept) if "</urlset>" in line]
        if not closing:
            raise BlogError("sitemap.xml has no </urlset> line")
        at = closing[-1]

    def url(loc: str, lastmod: dt.date, tail: str) -> str:
        return f"{indent}<url><loc>{loc}</loc><lastmod>{lastmod.isoformat()}</lastmod>{tails.get(loc, tail)}</url>\n"

    fresh = []
    if entries:
        fresh.append(url(f"{SITE}/blog", max(p.modified(through) for p in entries), TAIL_INDEX))
    fresh += [url(post.url, post.modified(through), TAIL_POST) for post in entries]
    return "".join(kept[:at] + fresh + kept[at:])


