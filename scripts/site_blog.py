def _scalar(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def split_front_matter(text: str, name: str) -> tuple[dict[str, str | list[str]], str]:
    """(front matter, Markdown body). The block is `key: value` lines between two --- lines."""
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        raise BlogError(f"{name}: the file must start with a front matter block (--- on the first line)")
    try:
        end = next(n for n in range(1, len(lines)) if lines[n].strip() == "---")
    except StopIteration:
        raise BlogError(f"{name}: the front matter block is never closed with ---") from None
    meta: dict[str, str | list[str]] = {}
    key = ""
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        item = re.match(r"^\s+-\s+(.*)$", line)
        if item:
            current = meta.get(key)
            if not key or not isinstance(current, list):
                raise BlogError(f"{name}: list item {line.strip()!r} does not follow a `key:` line")
            current.append(_scalar(item.group(1)))
            continue
        m = re.match(r"^([A-Za-z_]+):(.*)$", line)
        if not m:
            raise BlogError(f"{name}: cannot read front matter line {line.strip()!r}")
        key, value = m.group(1), m.group(2).strip()
        if key not in KEYS:
            raise BlogError(f"{name}: unknown front matter key {key!r} (known: {', '.join(sorted(KEYS))})")
        if key in meta:
            raise BlogError(f"{name}: front matter key {key!r} is given twice")
        if not value:
            meta[key] = []
        elif value.startswith("[") and value.endswith("]"):
            meta[key] = [_scalar(v) for v in value[1:-1].split(",") if v.strip()]
        elif key in LIST_KEYS:
            meta[key] = [_scalar(v) for v in value.split(",") if v.strip()]
        else:
            meta[key] = _scalar(value)
    return meta, "\n".join(lines[end + 1 :]).strip("\n")


def _date(value: object, name: str, key: str) -> dt.date:
    if not isinstance(value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        raise BlogError(f"{name}: {key} must be a date written YYYY-MM-DD, not {value!r}")
    try:
        return dt.date.fromisoformat(value)
    except ValueError:
        raise BlogError(f"{name}: {key} {value!r} is not a real date") from None


def _text(meta: dict[str, str | list[str]], key: str, name: str, default: str | None = None) -> str:
    value = meta.get(key, default)
    if not isinstance(value, str) or not value.strip():
        raise BlogError(f"{name}: front matter needs a {key}")
    return value.strip()


def parse_post(text: str, name: str) -> Post:
    """One post from its file text. `name` is the file name, which carries the date and the slug."""
    named = FILE_NAME.match(name)
    if not named:
        raise BlogError(f"{name}: post files are named <YYYY-MM-DD>-<slug>.md, lowercase letters, digits and hyphens")
    meta, body = split_front_matter(text, name)
    title = _text(meta, "title", name)
    description = _text(meta, "description", name)
    if not 50 <= len(description) <= 160:
        raise BlogError(f"{name}: description is {len(description)} characters; search results need 50 to 160")
    date = _date(meta.get("date"), name, "date")
    if date.isoformat() != named.group(1):
        raise BlogError(f"{name}: date {date} does not match the date in the file name")
    slug = _text(meta, "slug", name, named.group(2))
    if not SLUG.match(slug) or slug != named.group(2):
        raise BlogError(f"{name}: slug {slug!r} must match the file name ({named.group(2)})")
    if slug in ("index", "feed"):
        raise BlogError(f"{name}: slug {slug!r} is taken by the blog itself")
    updated = _date(meta["updated"], name, "updated") if "updated" in meta else None
    if updated is not None and updated < date:
        raise BlogError(f"{name}: updated {updated} is before date {date}")
    tags = meta.get("tags", [])
    if not isinstance(tags, list) or not 1 <= len(tags) <= 8 or len(set(tags)) != len(tags):
        raise BlogError(f"{name}: tags must be a list of 1 to 8 different tags")
    for tag in tags:
        if not TAG.match(tag):
            raise BlogError(f"{name}: tag {tag!r} must be 1 to 40 letters, digits, spaces or . + # / -")
    draft = meta.get("draft", "false")
    if draft not in ("true", "false"):
        raise BlogError(f"{name}: draft must be true or false, not {draft!r}")
    docs = meta.get("docs", [])
    if not isinstance(docs, list):
        raise BlogError(f"{name}: docs must be a list of docs paths")
    if not body.strip():
        raise BlogError(f"{name}: the post has no body")
    return Post(
        slug=slug,
        title=title,
        description=description,
        date=date,
        updated=updated,
        tags=tuple(tags),
        author=_text(meta, "author", name, DEFAULT_AUTHOR),
        draft=draft == "true",
        docs=tuple(d.strip().strip("/") for d in docs),
        lede=_text(meta, "lede", name, description),
        body=body,
        source=name,
    )


def load_legacy(paths: Paths) -> list[Post]:
    """The hand-written posts in landing/blog/: listed, never rewritten."""
    if not paths.legacy.is_file():
        return []
    name = paths.legacy.name
    try:
        rows = json.loads(paths.legacy.read_text(encoding="utf-8"))
    except json.JSONDecodeError as err:
        raise BlogError(f"{name}: not valid JSON ({err})") from None
    if not isinstance(rows, list):
        raise BlogError(f"{name}: must be a list of posts")
    posts = []
    for row in rows:
        if not isinstance(row, dict) or not SLUG.match(str(row.get("slug", ""))):
            raise BlogError(f"{name}: every entry needs a slug of lowercase letters, digits and hyphens")
        where = f"{name} ({row['slug']})"
        for key in ("title", "description"):
            if not isinstance(row.get(key), str) or not row[key].strip():
                raise BlogError(f"{where}: needs a {key}")
        date = _date(row.get("date"), where, "date")
        updated = _date(row["updated"], where, "updated") if "updated" in row else None
        if updated is not None and updated < date:
            raise BlogError(f"{where}: updated {updated} is before date {date}")
        if not (paths.blog / f"{row['slug']}.html").is_file():
            raise BlogError(f"{where}: landing/blog/{row['slug']}.html does not exist")
        posts.append(
            Post(
                slug=row["slug"],
                title=row["title"].strip(),
                description=row["description"].strip(),
                date=date,
                updated=updated,
                legacy=True,
            )
        )
    if len({p.slug for p in posts}) != len(posts):
        raise BlogError(f"{name}: a slug is listed twice")
    return posts


def load_posts(paths: Paths) -> list[Post]:
    """Every post in content/blog/, drafts and future dates included, checked against each other and the legacy list."""
    posts = []
    for path in sorted(paths.content.glob("*.md")) if paths.content.is_dir() else []:
        if path.name == "README.md":
            continue
        try:
            posts.append(parse_post(path.read_text(encoding="utf-8"), path.name))
        except BlogError as err:
            message = str(err)
            raise BlogError(message if message.startswith(path.name) else f"{path.name}: {message}") from None
    taken = {p.slug: f"the legacy post landing/blog/{p.slug}.html" for p in load_legacy(paths)}
    for post in posts:
        if post.slug in taken:
            raise BlogError(f"{post.source}: slug {post.slug!r} is already used by {taken[post.slug]}")
        taken[post.slug] = post.source
    return posts


def is_live(post: Post, through: dt.date) -> bool:
    return not post.draft and post.date <= through


