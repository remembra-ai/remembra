def ordered(posts: list[Post], through: dt.date) -> list[Post]:
    """Newest first, by the date readers see (a revised post moves up when its `updated` date comes)."""
    by_slug = sorted(posts, key=lambda p: p.slug)
    return sorted(by_slug, key=lambda p: (p.modified(through), p.date), reverse=True)


def build(paths: Paths, through: dt.date, preview: bool = False) -> dict[Path, str]:
    """Every file the blog is made of, with its content, as of `through`. Writes nothing.

    preview=True also renders drafts and future-dated posts (for --serve; never committed).
    """
    posts = load_posts(paths)
    live = [p for p in posts if preview or is_live(p, through)]
    if preview and live:
        through = max(through, max(p.updated or p.date for p in live))
    entries = ordered([*live, *load_legacy(paths)], through)
    known = {f"{p.slug}.html" for p in entries} | {"index.html"}
    for page in sorted(paths.blog.glob("*.html")) if paths.blog.is_dir() else []:
        if page.name not in known and MARKER not in page.read_text(encoding="utf-8"):
            raise BlogError(f"landing/blog/{page.name} is hand-written but not listed in content/blog/legacy.json")
    out = {paths.blog / f"{p.slug}.html": render_post(p, through) for p in live}
    out[paths.index] = render_index(entries, through)
    out[paths.feed] = render_feed(entries, through)
    out[paths.sitemap] = render_sitemap(paths.sitemap.read_text(encoding="utf-8"), entries, through)
    return out


def orphans(paths: Paths, outputs: dict[Path, str]) -> list[Path]:
    """Pages this script wrote for posts that are no longer published (unpublished, renamed or re-dated)."""
    if not paths.blog.is_dir():
        return []
    return [
        page for page in sorted(paths.blog.glob("*.html")) if page not in outputs and MARKER in page.read_text(encoding="utf-8")
    ]


def stale(paths: Paths, outputs: dict[Path, str]) -> list[Path]:
    return [path for path, text in outputs.items() if not path.is_file() or path.read_text(encoding="utf-8") != text]


def built_through(paths: Paths) -> dt.date | None:
    if not paths.build.is_file():
        return None
    try:
        return _date(json.loads(paths.build.read_text(encoding="utf-8")).get("built_through"), paths.build.name, "built_through")
    except (json.JSONDecodeError, AttributeError):
        raise BlogError(f'{paths.build.name}: must be {{"built_through": "YYYY-MM-DD"}}') from None


def check(paths: Paths) -> list[str]:
    """What is out of date in the committed output, rendered as of the recorded build date (never the clock)."""
    through = built_through(paths)
    if through is None:
        return [f"{paths.build.name} is missing: run python scripts/site_blog.py"]
    outputs = build(paths, through)
    problems = [f"{p.relative_to(paths.landing.parent).as_posix()} is stale" for p in stale(paths, outputs)]
    problems += [f"{p.relative_to(paths.landing.parent).as_posix()} has no published post" for p in orphans(paths, outputs)]
    return problems


def write(paths: Paths, today: dt.date) -> dict[str, object]:
    """Rebuild the blog as of `today` and report what changed.

    build.json moves to `today` only when the output changed (or would differ from a build as of the recorded
    date), so a run on a day when nothing comes due leaves the tree untouched.
    """
    recorded = built_through(paths)
    outputs = build(paths, today)
    changed = stale(paths, outputs)
    removed = orphans(paths, outputs)
    posts = {paths.blog / f"{p.slug}.html": p for p in load_posts(paths)}
    added = [posts[path] for path in changed if path in posts and not path.is_file()]
    unchanged = recorded is not None and not changed and not removed and (recorded == today or build(paths, recorded) == outputs)
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
    for path in removed:
        path.unlink()
    if not unchanged:
        paths.build.parent.mkdir(parents=True, exist_ok=True)
        paths.build.write_text(json.dumps({"built_through": today.isoformat()}, indent=2) + "\n", encoding="utf-8")
    titles = ", ".join(p.title for p in ordered(added, today))
    title = f"Publish: {titles}" if titles else f"Publish: blog update {today.isoformat()}"
    return {
        "built_through": (recorded if unchanged and recorded else today).isoformat(),
        "changed": bool(changed or removed),
        "written": sorted(p.relative_to(paths.landing.parent).as_posix() for p in changed),
        "removed": sorted(p.relative_to(paths.landing.parent).as_posix() for p in removed),
        "published": [{"slug": p.slug, "title": p.title, "date": p.date.isoformat()} for p in ordered(added, today)],
        "pr_title": title if len(title) <= 120 else title[:117].rstrip() + "...",
    }


def pending(paths: Paths, through: dt.date) -> list[str]:
    """One line per post that is not in the output yet: waiting on its date, or a draft."""
    lines = []
    for post in sorted(load_posts(paths), key=lambda p: (p.date, p.slug)):
        if post.draft:
            lines.append(f"{post.date}  draft      {post.slug}  {post.title}")
        elif post.date > through:
            lines.append(f"{post.date}  scheduled  {post.slug}  {post.title}")
    return lines


