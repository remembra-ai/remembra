def clean_url_file(root: Path, url: str) -> Path | None:
    """The file landing/nginx.conf's try_files would serve for a URL: the path, then .html, then /index.html."""
    rel = unquote(urlsplit(url).path).lstrip("/")
    base = (root / rel).resolve()
    if base != root.resolve() and root.resolve() not in base.parents:
        return None
    for candidate in (base, base.with_name(base.name + ".html") if rel else base, base / "index.html"):
        if candidate.is_file():
            return candidate
    return None


def serve(paths: Paths, today: dt.date, port: int) -> int:
    """Copy landing/ to a temporary folder, add every post (drafts and future dates too) and serve it with clean URLs."""
    import shutil
    import tempfile
    from functools import partial
    from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

    with tempfile.TemporaryDirectory(prefix="remembra-blog-") as tmp:
        root = Path(tmp) / "landing"
        shutil.copytree(paths.landing, root, ignore=shutil.ignore_patterns("node_modules"))
        preview = Paths(content=paths.content, landing=root)
        for path, text in build(preview, today, preview=True).items():
            path.write_text(text, encoding="utf-8")

        class Handler(SimpleHTTPRequestHandler):
            def translate_path(self, path: str) -> str:
                found = clean_url_file(root, path)
                return str(found) if found else super().translate_path(path)

        server = ThreadingHTTPServer(("127.0.0.1", port), partial(Handler, directory=str(root)))
        print(f"Preview with drafts and scheduled posts: http://127.0.0.1:{port}/blog  (Ctrl-C to stop)")
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            print()
        finally:
            server.server_close()
    return 0


