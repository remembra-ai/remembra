FENCE = re.compile(r"^(`{3,}|~{3,})[ \t]*([^\s`]*)[^`]*$")
HEADING = re.compile(r"^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$")
BULLET = re.compile(r"^[-*+][ \t]+(.*)$")
NUMBER = re.compile(r"^\d{1,9}[.)][ \t]+(.*)$")
RULE = re.compile(r"^(?:-{3,}|\*{3,}|_{3,})[ \t]*$")
TABLE_RULE = re.compile(r"^\|?[ \t]*:?-+:?[ \t]*(?:\|[ \t]*:?-+:?[ \t]*)*\|?$")
LANGUAGE = re.compile(r"^[A-Za-z0-9_+#.-]+$")
INLINE_CODE = re.compile(r"\\([!-/:-@\[-`{-~])|(`+)(.+?)(?<!`)\2(?!`)")
INLINE_LINK = re.compile(r'(!?)\[([^\]]*)\]\(\s*([^()\s]*(?:\([^()\s]*\)[^()\s]*)*)(?:\s+"([^"]*)")?\s*\)')
SLOT = re.compile("\x00(\\d+)\x00")


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def plain_text(fragment: str) -> str:
    """The text of an HTML fragment this renderer made (tags dropped, entities decoded)."""
    return html.unescape(re.sub(r"<[^>]+>", "", fragment))


def check_url(url: str, what: str = "link") -> str:
    """A link target the site allows: https, mailto, a site path (/pricing) or an anchor (#id)."""
    if url.startswith("#") and len(url) > 1:
        return url
    if url.startswith("/") and not url.startswith("//") and "\\" not in url:
        return url
    parts = urlsplit(url)
    if parts.scheme == "https" and parts.netloc:
        return url
    if parts.scheme == "mailto" and parts.path:
        return url
    raise BlogError(f"{what} target {url!r} is not allowed: use https://, mailto:, a site path such as /pricing, or #anchor")


class Markdown:
    """Render the supported Markdown subset to HTML. Everything that is not markup is escaped."""

    def __init__(self) -> None:
        self.links: list[str] = []
        self.ids: list[str] = []

    def render(self, text: str) -> str:
        lines = text.replace("\x00", "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
        return "\n".join(self._blocks(lines))

    # -- inline ----------------------------------------------------------------

    def inline(self, text: str) -> str:
        slots: list[str] = []

        def stash(fragment: str) -> str:
            slots.append(fragment)
            return f"\x00{len(slots) - 1}\x00"

        def restore(fragment: str) -> str:
            while SLOT.search(fragment):
                fragment = SLOT.sub(lambda m: slots[int(m.group(1))], fragment)
            return fragment

        def code(m: re.Match[str]) -> str:
            if m.group(1) is not None:  # a backslash escape: the character itself
                return stash(html.escape(m.group(1), quote=False))
            body = m.group(3)
            if body.startswith(" ") and body.endswith(" ") and body.strip():
                body = body[1:-1]
            return stash(f"<code>{html.escape(body, quote=False)}</code>")

        def link(m: re.Match[str]) -> str:
            image, label, url, title = m.group(1), m.group(2), m.group(3), m.group(4)
            if "\x00" in url:  # a backslash escape inside the target: back to the character itself
                url = plain_text(restore(url))
            if not url:
                raise BlogError(f"link [{plain_text(restore(label))}] has no target")
            if image:
                if not label.strip():
                    raise BlogError(f"image {url!r} needs alt text: ![what it shows]({url})")
                if not url.startswith("/") or url.startswith("//"):
                    raise BlogError(f"image {url!r} must be a file on this site, such as /blog/img/name.png")
                self.links.append(url)
                alt = html.escape(plain_text(restore(emphasis(label))), quote=True)
                return stash(f'<img src="{html.escape(url, quote=True)}" alt="{alt}" loading="lazy">')
            if not label.strip():
                raise BlogError(f"link to {url!r} has no text")
            check_url(url)
            self.links.append(url)
            attr = f' title="{html.escape(title, quote=True)}"' if title else ""
            return stash(f'<a href="{html.escape(url, quote=True)}"{attr}>{restore(emphasis(label))}</a>')

        def emphasis(fragment: str) -> str:
            fragment = html.escape(fragment, quote=False)
            fragment = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", fragment)
            fragment = re.sub(r"(?<!\w)__(?=\S)(.+?)(?<=\S)__(?!\w)", r"<strong>\1</strong>", fragment)
            fragment = re.sub(r"\*(?=\S)([^*]+?)(?<=\S)\*", r"<em>\1</em>", fragment)
            return re.sub(r"(?<!\w)_(?=\S)([^_]+?)(?<=\S)_(?!\w)", r"<em>\1</em>", fragment)

        text = INLINE_CODE.sub(code, text)
        text = INLINE_LINK.sub(link, text)
        return restore(emphasis(text))

    def _paragraph(self, lines: list[str]) -> str:
        parts = []
        for n, line in enumerate(lines):
            last = n == len(lines) - 1
            hard = not last and (line.endswith("  ") or line.endswith("\\"))
            body = self.inline(line.rstrip(" \\") if hard else line.strip())
            parts.append(body + ("<br>" if hard else ""))
        return "\n".join(parts)

    # -- blocks ----------------------------------------------------------------

    def _heading_id(self, title_html: str) -> str:
        base = slugify(plain_text(title_html)) or "section"
        candidate, n = base, 1
        while candidate in self.ids or candidate in RESERVED_IDS:
            n += 1
            candidate = f"{base}-{n}"
        self.ids.append(candidate)
        return candidate

    @staticmethod
    def _starts_block(line: str) -> bool:
        return bool(FENCE.match(line) or HEADING.match(line) or line.startswith(">") or BULLET.match(line) or NUMBER.match(line))

    def _blocks(self, lines: list[str]) -> list[str]:
        out: list[str] = []
        i = 0
        while i < len(lines):
            line = lines[i]
            if not line.strip():
                i += 1
                continue
            fence = FENCE.match(line)
            if fence:
                i = self._code(lines, i, fence, out)
            elif HEADING.match(line):
                out.append(self._heading(line))
                i += 1
            elif RULE.match(line):
                raise BlogError(f"horizontal rules ({line.strip()}) are not supported: use a heading")
            elif line.startswith(">"):
                quoted = []
                while i < len(lines) and lines[i].startswith(">"):
                    quoted.append(re.sub(r"^> ?", "", lines[i]))
                    i += 1
                out.append("<blockquote>\n" + "\n".join(self._blocks(quoted)) + "\n</blockquote>")
            elif BULLET.match(line) or NUMBER.match(line):
                i = self._list(lines, i, out)
            elif "|" in line and i + 1 < len(lines) and "|" in lines[i + 1] and TABLE_RULE.match(lines[i + 1].strip()):
                i = self._table(lines, i, out)
            else:
                para = []
                while i < len(lines) and lines[i].strip() and not (para and self._starts_block(lines[i])):
                    para.append(lines[i])
                    i += 1
                out.append(f"<p>{self._paragraph(para)}</p>")
        return out

    def _code(self, lines: list[str], i: int, fence: re.Match[str], out: list[str]) -> int:
        mark, language = fence.group(1), fence.group(2)
        if language and not LANGUAGE.match(language):
            raise BlogError(f"code fence language {language!r} is not a plain name")
        closing = re.compile(rf"^{re.escape(mark[0])}{{{len(mark)},}}[ \t]*$")
        body = []
        i += 1
        while i < len(lines) and not closing.match(lines[i]):
            body.append(lines[i])
            i += 1
        if i == len(lines):
            raise BlogError(f"code fence {mark} is never closed")
        cls = f' class="language-{language}"' if language else ""
        out.append(f"<pre><code{cls}>{html.escape(chr(10).join(body), quote=False)}</code></pre>")
        return i + 1

    def _heading(self, line: str) -> str:
        m = HEADING.match(line)
        assert m is not None
        level = len(m.group(1))
        if level == 1:
            raise BlogError(f"{line.strip()!r}: the page's h1 is the post title; start headings at ##")
        if level > 4:
            raise BlogError(f"{line.strip()!r}: headings go from ## to ####")
        body = self.inline(m.group(2))
        return f'<h{level} id="{self._heading_id(body)}">{body}</h{level}>'

    def _list(self, lines: list[str], i: int, out: list[str]) -> int:
        marker = BULLET if BULLET.match(lines[i]) else NUMBER
        tag = "ul" if marker is BULLET else "ol"
        items: list[list[str]] = []
        while i < len(lines):
            line = lines[i]
            m = marker.match(line)
            if m:
                items.append([m.group(1)])
                i += 1
            elif line.strip() and line[:1] in " \t":
                if BULLET.match(line.strip()) or NUMBER.match(line.strip()):
                    raise BlogError(f"{line.strip()!r}: nested lists are not supported")
                items[-1].append(line.strip())
                i += 1
            elif not line.strip() and i + 1 < len(lines) and marker.match(lines[i + 1]):
                i += 1  # a blank line between two items of the same list
            else:
                break
        body = "\n".join(f"<li>{self._paragraph(item)}</li>" for item in items)
        out.append(f"<{tag}>\n{body}\n</{tag}>")
        return i

    @staticmethod
    def _cells(row: str) -> list[str]:
        row = row.strip()
        row = row[1:] if row.startswith("|") else row
        row = row[:-1] if row.endswith("|") and not row.endswith("\\|") else row
        return [cell.strip().replace("\\|", "|") for cell in re.split(r"(?<!\\)\|", row)]

    def _table(self, lines: list[str], i: int, out: list[str]) -> int:
        head = self._cells(lines[i])
        if len(self._cells(lines[i + 1])) != len(head):
            raise BlogError(f"table {lines[i].strip()!r}: the header and the rule under it differ in columns")
        rows = []
        i += 2
        while i < len(lines) and lines[i].strip() and "|" in lines[i]:
            cells = self._cells(lines[i])
            if len(cells) > len(head):
                raise BlogError(f"table row {lines[i].strip()!r} has more cells than the header")
            rows.append(cells + [""] * (len(head) - len(cells)))
            i += 1
        thead = "<tr>" + "".join(f"<th>{self.inline(c)}</th>" for c in head) + "</tr>"
        tbody = "\n".join("<tr>" + "".join(f"<td>{self.inline(c)}</td>" for c in row) + "</tr>" for row in rows)
        out.append(f"<table>\n<thead>\n{thead}\n</thead>\n<tbody>\n{tbody}\n</tbody>\n</table>")
        return i


def render_markdown(text: str) -> str:
    return Markdown().render(text)


