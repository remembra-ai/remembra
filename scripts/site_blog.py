def when(post: Post, through: dt.date) -> str:
    """The date line: the publish date, or "Updated ..." once the post has been revised."""
    day = post.modified(through)
    stamp = f'<time datetime="{day.isoformat()}">{long_date(day)}</time>'
    return f"Updated {stamp}" if day != post.date else stamp


