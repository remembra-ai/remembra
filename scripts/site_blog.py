"""Build the blog on remembra.dev from Markdown posts in content/blog/.

landing/ is served as it is committed (landing/Dockerfile copies the folder; there is no
build step), so the pages this script writes are committed too, and the post sources live
outside landing/ so they are never published as files.

    python scripts/site_blog.py                     # rebuild with today's date (UTC)
    python scripts/site_blog.py --today 2027-01-05  # rebuild as of that date
    python scripts/site_blog.py --check             # exit 1 if the committed output is stale
    python scripts/site_blog.py --pending           # posts waiting on a future date, and drafts
    python scripts/site_blog.py --serve             # preview everything, drafts included, on localhost

Sources:

    content/blog/<YYYY-MM-DD>-<slug>.md   one post: front matter, then Markdown
    content/blog/legacy.json              the hand-written posts already in landing/blog/
    content/blog/build.json               {"built_through": "YYYY-MM-DD"}: the date the output was built for

Outputs (all committed):

    landing/blog/<slug>.html   one page per published post, chrome filled by site_partials.render()
    landing/blog/index.html    every post, newest first
    landing/feed.xml           RSS 2.0, the latest 20 posts
    landing/sitemap.xml        only its /blog lines are rewritten

A post is published when it is not a draft and its date is on or before the build date.
--check renders with the date recorded in build.json, never the clock, so the test suite
gives the same answer on any day. A run that changes no output leaves build.json alone, so
the daily workflow (.github/workflows/blog-publish.yml) produces a diff only when a post
comes due.

The Markdown renderer is a deliberate subset with no dependency: ## to #### headings with
id anchors, paragraphs, fenced code, inline code, bold, italic, links, images, one-level
lists, blockquotes and pipe tables. Raw HTML is not passed through: it is escaped.
"""

