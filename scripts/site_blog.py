def docs_title(source: str) -> str:
    """The name mkdocs.yml's nav gives a docs page, or its path when the nav does not name it."""
    nav = re.search(rf"^\s*-\s*(.+?):\s*{re.escape(source)}\s*$", site_predeploy.MKDOCS.read_text(encoding="utf-8"), re.M)
    return _scalar(nav.group(1)) if nav else source.removesuffix(".md")


def related_docs(post: Post) -> list[tuple[str, str]]:
    """(url, title) for each `docs:` path, every one a page mkdocs.yml builds."""
    out = []
    for path in post.docs:
        url = f"https://{DOCS_HOST}/{path}/" if path else f"https://{DOCS_HOST}/"
        source = site_predeploy.source_for(url) if not path or DOCS_PATH.match(path) else None
        if source is None:
            raise BlogError(f"{post.source}: docs path {path!r} is not a page mkdocs.yml builds from docs/")
        out.append((url, docs_title(source)))
    return out


def check_links(post: Post, links: list[str], ids: list[str]) -> None:
    for url in links:
        if url.startswith("#"):
            if url[1:] not in ids:
                raise BlogError(
                    f"{post.source}: link {url} matches no heading in the post (headings: {', '.join(ids) or 'none'})"
                )
            continue
        parts = urlsplit(url)
        if parts.netloc == DOCS_HOST and site_predeploy.source_for(url) is None:
            raise BlogError(f"{post.source}: {url} is not a page mkdocs.yml builds from docs/")


