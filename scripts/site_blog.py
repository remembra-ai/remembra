def main(argv: list[str], paths: Paths = DEFAULT_PATHS) -> int:
    parser = argparse.ArgumentParser(description="Build the remembra.dev blog from content/blog/.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed output is stale")
    parser.add_argument("--today", metavar="YYYY-MM-DD", help="build as of this date instead of today (UTC)")
    parser.add_argument("--pending", action="store_true", help="list posts waiting on a future date, and drafts")
    parser.add_argument("--report", metavar="FILE", help="write what changed as JSON (the publish workflow reads it)")
    parser.add_argument("--serve", nargs="?", const=8080, type=int, metavar="PORT", help="preview locally, drafts included")
    args = parser.parse_args(argv)
    try:
        if args.check:  # as of the recorded build date: the clock is never read
            problems = check(paths)
            if problems:
                print("\n".join(problems))
                print("run python scripts/site_blog.py")
                return 1
            print(f"up to date (built through {built_through(paths)})")
            return 0
        today = _date(args.today, "--today", "the date") if args.today else dt.datetime.now(dt.UTC).date()
        if args.serve is not None:
            return serve(paths, today, args.serve)
        if args.pending:
            through = today if args.today else (built_through(paths) or today)
            lines = pending(paths, through)
            print("\n".join(lines) if lines else f"nothing pending (built through {through})")
            return 0
        report = write(paths, today)
    except BlogError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    if args.report:
        Path(args.report).write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    if report["changed"]:
        print("updated: " + ", ".join([*report["written"], *(f"{name} (removed)" for name in report["removed"])]))  # type: ignore[misc]
    else:
        print(f"nothing to do (built through {report['built_through']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
